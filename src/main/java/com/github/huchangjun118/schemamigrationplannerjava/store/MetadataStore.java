package com.github.huchangjun118.schemamigrationplannerjava.store;

import com.github.huchangjun118.schemamigrationplannerjava.model.SchemaDefinition;
import com.github.huchangjun118.schemamigrationplannerjava.model.SchemaVersion;
import com.github.huchangjun118.schemamigrationplannerjava.plan.MigrationPlan;
import com.github.huchangjun118.schemamigrationplannerjava.plan.PlanStatus;
import com.github.huchangjun118.schemamigrationplannerjava.util.JsonUtils;
import jakarta.annotation.PostConstruct;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Component;

import java.sql.PreparedStatement;
import java.sql.Statement;
import java.time.Instant;
import java.util.List;
import java.util.Optional;

/**
 * 元数据存储（本地嵌入式 H2）。承载结构版本、变更计划、步骤执行状态、
 * 回填进度、执行租约、审计日志与操作者角色。所有表位于 META schema。
 *
 * <p>版本记录与审计日志只追加、不更新、不删除，保证全程可追溯、不可改写。
 */
@Component
public class MetadataStore {

    public static final String META = "META";

    private final JdbcTemplate jdbc;

    public MetadataStore(@Qualifier("metadataJdbcTemplate") JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @PostConstruct
    public void init() {
        jdbc.execute("CREATE SCHEMA IF NOT EXISTS \"" + META + "\"");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."schema_version" (
                    "version_id"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "schema_name"  VARCHAR(255) NOT NULL,
                    "snapshot"     CLOB NOT NULL,
                    "created_at"   VARCHAR(64) NOT NULL,
                    "operator"     VARCHAR(255) NOT NULL,
                    "comment"      VARCHAR(1000)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."migration_plan" (
                    "plan_id"         VARCHAR(64) PRIMARY KEY,
                    "schema_name"     VARCHAR(255) NOT NULL,
                    "from_version"    BIGINT NOT NULL,
                    "to_version"      BIGINT NOT NULL,
                    "kind"            VARCHAR(16) NOT NULL,
                    "plan_json"       CLOB NOT NULL,
                    "status"          VARCHAR(32) NOT NULL,
                    "created_at"      VARCHAR(64) NOT NULL,
                    "operator"        VARCHAR(255) NOT NULL,
                    "failure_reason"  VARCHAR(2000)
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."step_execution" (
                    "plan_id"       VARCHAR(64) NOT NULL,
                    "step_index"    INT NOT NULL,
                    "step_type"     VARCHAR(64) NOT NULL,
                    "status"        VARCHAR(32) NOT NULL,
                    "started_at"    VARCHAR(64),
                    "completed_at"  VARCHAR(64),
                    "last_error"    VARCHAR(2000),
                    PRIMARY KEY ("plan_id", "step_index")
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."backfill_progress" (
                    "plan_id"         VARCHAR(64) NOT NULL,
                    "step_index"      INT NOT NULL,
                    "table_name"      VARCHAR(255) NOT NULL,
                    "column_name"     VARCHAR(255) NOT NULL,
                    "last_key"        BIGINT NOT NULL DEFAULT 0,
                    "processed_rows"  BIGINT NOT NULL DEFAULT 0,
                    "status"          VARCHAR(32) NOT NULL,
                    "updated_at"      VARCHAR(64) NOT NULL,
                    PRIMARY KEY ("plan_id", "step_index")
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."lease" (
                    "lease_key"    VARCHAR(255) PRIMARY KEY,
                    "owner"        VARCHAR(255) NOT NULL,
                    "acquired_at"  VARCHAR(64) NOT NULL,
                    "expires_at"   VARCHAR(64) NOT NULL,
                    "token"        VARCHAR(64) NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."audit_log" (
                    "id"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "plan_id"          VARCHAR(64),
                    "action"           VARCHAR(64) NOT NULL,
                    "operator"         VARCHAR(255) NOT NULL,
                    "detail"           CLOB,
                    "before_snapshot"  CLOB,
                    "after_snapshot"   CLOB,
                    "created_at"       VARCHAR(64) NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS "META"."operator_role" (
                    "operator"  VARCHAR(255) PRIMARY KEY,
                    "role"      VARCHAR(32) NOT NULL
                )
                """);
    }

    // ===== 结构版本（只追加） =====

    public long insertVersion(String schemaName, SchemaDefinition snapshot, String operator, String comment) {
        KeyHolder kh = new GeneratedKeyHolder();
        jdbc.update(con -> {
            PreparedStatement ps = con.prepareStatement(
                    "INSERT INTO \"META\".\"schema_version\" " +
                            "(\"schema_name\",\"snapshot\",\"created_at\",\"operator\",\"comment\") " +
                            "VALUES (?,?,?,?,?)", Statement.RETURN_GENERATED_KEYS);
            ps.setString(1, schemaName);
            ps.setString(2, JsonUtils.toJson(snapshot));
            ps.setString(3, Instant.now().toString());
            ps.setString(4, operator);
            ps.setString(5, comment);
            return ps;
        }, kh);
        return kh.getKey().longValue();
    }

    public Optional<SchemaVersion> getLatestVersion(String schemaName) {
        List<SchemaVersion> list = jdbc.query(
                "SELECT * FROM \"META\".\"schema_version\" WHERE \"schema_name\"=? " +
                        "ORDER BY \"version_id\" DESC LIMIT 1",
                (rs, n) -> new SchemaVersion(
                        rs.getLong("version_id"),
                        rs.getString("schema_name"),
                        JsonUtils.fromJson(rs.getString("snapshot"), SchemaDefinition.class),
                        rs.getString("created_at"),
                        rs.getString("operator"),
                        rs.getString("comment")),
                schemaName);
        return list.stream().findFirst();
    }

    public Optional<SchemaVersion> getVersion(long versionId) {
        List<SchemaVersion> list = jdbc.query(
                "SELECT * FROM \"META\".\"schema_version\" WHERE \"version_id\"=?",
                (rs, n) -> new SchemaVersion(
                        rs.getLong("version_id"),
                        rs.getString("schema_name"),
                        JsonUtils.fromJson(rs.getString("snapshot"), SchemaDefinition.class),
                        rs.getString("created_at"),
                        rs.getString("operator"),
                        rs.getString("comment")),
                versionId);
        return list.stream().findFirst();
    }

    public List<SchemaVersion> listVersions(String schemaName) {
        return jdbc.query(
                "SELECT * FROM \"META\".\"schema_version\" WHERE \"schema_name\"=? " +
                        "ORDER BY \"version_id\"",
                (rs, n) -> new SchemaVersion(
                        rs.getLong("version_id"),
                        rs.getString("schema_name"),
                        JsonUtils.fromJson(rs.getString("snapshot"), SchemaDefinition.class),
                        rs.getString("created_at"),
                        rs.getString("operator"),
                        rs.getString("comment")),
                schemaName);
    }

    // ===== 变更计划 =====

    public void insertPlan(MigrationPlan plan) {
        jdbc.update("INSERT INTO \"META\".\"migration_plan\" " +
                        "(\"plan_id\",\"schema_name\",\"from_version\",\"to_version\",\"kind\"," +
                        "\"plan_json\",\"status\",\"created_at\",\"operator\",\"failure_reason\") " +
                        "VALUES (?,?,?,?,?,?,?,?,?,?)",
                plan.planId(), plan.schemaName(), plan.fromVersion(), plan.toVersion(),
                plan.kind().name(), JsonUtils.toJson(plan), plan.status().name(),
                plan.createdAt(), plan.operator(), plan.failureReason());
    }

    public void updatePlanStatus(String planId, PlanStatus status, String failureReason) {
        jdbc.update("UPDATE \"META\".\"migration_plan\" SET \"status\"=?,\"failure_reason\"=? " +
                        "WHERE \"plan_id\"=?", status.name(), failureReason, planId);
    }

    public Optional<MigrationPlan> getPlan(String planId) {
        List<MigrationPlan> list = jdbc.query(
                "SELECT * FROM \"META\".\"migration_plan\" WHERE \"plan_id\"=?",
                (rs, n) -> {
                    MigrationPlan p = JsonUtils.fromJson(rs.getString("plan_json"), MigrationPlan.class);
                    // 以 status/failure_reason 列为准（plan_json 中的状态是插入时的旧值）
                    String status = rs.getString("status");
                    String failureReason = rs.getString("failure_reason");
                    return new MigrationPlan(p.planId(), p.schemaName(), p.fromVersion(), p.toVersion(),
                            p.kind(), p.steps(), PlanStatus.valueOf(status), p.createdAt(),
                            p.operator(), failureReason);
                },
                planId);
        return list.stream().findFirst();
    }

    public List<MigrationPlan> listPlans(String schemaName) {
        return jdbc.query(
                "SELECT * FROM \"META\".\"migration_plan\" WHERE \"schema_name\"=? " +
                        "ORDER BY \"created_at\"",
                (rs, n) -> JsonUtils.fromJson(rs.getString("plan_json"), MigrationPlan.class),
                schemaName);
    }

    // ===== 步骤执行状态 =====

    public void upsertStepState(String planId, int stepIndex, String stepType, String status,
                                String startedAt, String completedAt, String lastError) {
        jdbc.update("MERGE INTO \"META\".\"step_execution\" " +
                        "(\"plan_id\",\"step_index\",\"step_type\",\"status\",\"started_at\"," +
                        "\"completed_at\",\"last_error\") KEY(\"plan_id\",\"step_index\") " +
                        "VALUES (?,?,?,?,?,?,?)",
                planId, stepIndex, stepType, status, startedAt, completedAt, lastError);
    }

    public List<StepState> getStepStates(String planId) {
        return jdbc.query(
                "SELECT * FROM \"META\".\"step_execution\" WHERE \"plan_id\"=? ORDER BY \"step_index\"",
                (rs, n) -> new StepState(
                        rs.getInt("step_index"), rs.getString("step_type"),
                        rs.getString("status"), rs.getString("started_at"),
                        rs.getString("completed_at"), rs.getString("last_error")),
                planId);
    }

    /** 步骤执行状态（不可变记录） */
    public record StepState(int stepIndex, String stepType, String status,
                            String startedAt, String completedAt, String lastError) {
    }

    // ===== 回填进度 =====

    public void upsertProgress(String planId, int stepIndex, String tableName, String columnName,
                               long lastKey, long processedRows, String status) {
        jdbc.update("MERGE INTO \"META\".\"backfill_progress\" " +
                        "(\"plan_id\",\"step_index\",\"table_name\",\"column_name\",\"last_key\"," +
                        "\"processed_rows\",\"status\",\"updated_at\") " +
                        "KEY(\"plan_id\",\"step_index\") VALUES (?,?,?,?,?,?,?,?)",
                planId, stepIndex, tableName, columnName, lastKey, processedRows, status,
                Instant.now().toString());
    }

    public Optional<BackfillProgress> getProgress(String planId, int stepIndex) {
        List<BackfillProgress> list = jdbc.query(
                "SELECT * FROM \"META\".\"backfill_progress\" " +
                        "WHERE \"plan_id\"=? AND \"step_index\"=?",
                (rs, n) -> new BackfillProgress(
                        rs.getInt("step_index"), rs.getString("table_name"),
                        rs.getString("column_name"), rs.getLong("last_key"),
                        rs.getLong("processed_rows"), rs.getString("status"),
                        rs.getString("updated_at")),
                planId, stepIndex);
        return list.stream().findFirst();
    }

    /** 回填进度（不可变记录） */
    public record BackfillProgress(int stepIndex, String tableName, String columnName,
                                   long lastKey, long processedRows, String status,
                                   String updatedAt) {
    }

    // ===== 租约 =====

    public int insertLease(String key, String owner, String acquiredAt, String expiresAt, String token) {
        return jdbc.update("INSERT INTO \"META\".\"lease\" " +
                        "(\"lease_key\",\"owner\",\"acquired_at\",\"expires_at\",\"token\") " +
                        "VALUES (?,?,?,?,?)",
                key, owner, acquiredAt, expiresAt, token);
    }

    public int updateLeaseIfExpired(String key, String owner, String acquiredAt,
                                    String expiresAt, String token, String now) {
        return jdbc.update("UPDATE \"META\".\"lease\" SET \"owner\"=?,\"acquired_at\"=?," +
                        "\"expires_at\"=?,\"token\"=? WHERE \"lease_key\"=? AND \"expires_at\"<?",
                owner, acquiredAt, expiresAt, token, key, now);
    }

    public int renewLease(String key, String token, String newExpiresAt) {
        return jdbc.update("UPDATE \"META\".\"lease\" SET \"expires_at\"=? " +
                        "WHERE \"lease_key\"=? AND \"token\"=?",
                newExpiresAt, key, token);
    }

    public int releaseLease(String key, String token) {
        return jdbc.update("DELETE FROM \"META\".\"lease\" " +
                        "WHERE \"lease_key\"=? AND \"token\"=?", key, token);
    }

    public Optional<LeaseRow> getLease(String key) {
        List<LeaseRow> list = jdbc.query(
                "SELECT * FROM \"META\".\"lease\" WHERE \"lease_key\"=?",
                (rs, n) -> new LeaseRow(rs.getString("lease_key"), rs.getString("owner"),
                        rs.getString("acquired_at"), rs.getString("expires_at"),
                        rs.getString("token")),
                key);
        return list.stream().findFirst();
    }

    public List<LeaseRow> listLeases() {
        return jdbc.query("SELECT * FROM \"META\".\"lease\"",
                (rs, n) -> new LeaseRow(rs.getString("lease_key"), rs.getString("owner"),
                        rs.getString("acquired_at"), rs.getString("expires_at"),
                        rs.getString("token")));
    }

    /** 租约行 */
    public record LeaseRow(String key, String owner, String acquiredAt,
                           String expiresAt, String token) {
    }

    // ===== 审计（只追加） =====

    public void appendAudit(String planId, String action, String operator, String detail,
                            String beforeSnapshot, String afterSnapshot) {
        jdbc.update("INSERT INTO \"META\".\"audit_log\" " +
                        "(\"plan_id\",\"action\",\"operator\",\"detail\"," +
                        "\"before_snapshot\",\"after_snapshot\",\"created_at\") " +
                        "VALUES (?,?,?,?,?,?,?)",
                planId, action, operator, detail, beforeSnapshot, afterSnapshot,
                Instant.now().toString());
    }

    public List<AuditRow> listAudit() {
        return jdbc.query("SELECT * FROM \"META\".\"audit_log\" ORDER BY \"id\"",
                (rs, n) -> new AuditRow(
                        rs.getLong("id"), rs.getString("plan_id"), rs.getString("action"),
                        rs.getString("operator"), rs.getString("detail"),
                        rs.getString("before_snapshot"), rs.getString("after_snapshot"),
                        rs.getString("created_at")));
    }

    /** 审计行 */
    public record AuditRow(long id, String planId, String action, String operator,
                           String detail, String beforeSnapshot, String afterSnapshot,
                           String createdAt) {
    }

    // ===== 操作者角色 =====

    public Optional<String> getRole(String operator) {
        List<String> list = jdbc.query(
                "SELECT \"role\" FROM \"META\".\"operator_role\" WHERE \"operator\"=?",
                (rs, n) -> rs.getString("role"), operator);
        return list.stream().findFirst();
    }

    public void setRole(String operator, String role) {
        jdbc.update("MERGE INTO \"META\".\"operator_role\" (\"operator\",\"role\") " +
                        "KEY(\"operator\") VALUES (?,?)", operator, role);
    }

    public List<RoleRow> listRoles() {
        return jdbc.query("SELECT * FROM \"META\".\"operator_role\"",
                (rs, n) -> new RoleRow(rs.getString("operator"), rs.getString("role")));
    }

    /** 角色行 */
    public record RoleRow(String operator, String role) {
    }
}
